// Compute prev/next per lesson by global order
const sortedLessons = [...LESSONS].sort((a, b) => {
  const ai = SECTIONS_META.findIndex(s => s.id === a.sectionId)
  const bi = SECTIONS_META.findIndex(s => s.id === b.sectionId)
  if (ai !== bi) return ai - bi
  return a.order - b.order
})
sortedLessons.forEach((lesson, i) => {
  lesson.prevSlug = sortedLessons[i - 1]?.slug
  lesson.nextSlug = sortedLessons[i + 1]?.slug
})

export function getLessonBySlug(slug: string): Lesson | undefined {
  return LESSONS.find(l => l.slug === slug)
}

export function getLessonsBySection(sectionId: string): Lesson[] {
  return LESSONS.filter(l => l.sectionId === sectionId).sort((a, b) => a.order - b.order)
}

export function getSectionMeta(sectionId: string): SectionMeta | undefined {
  return SECTIONS_META.find(s => s.id === sectionId)
}

export function getAllSlugs(): string[] {
  return LESSONS.map(l => l.slug)
}
